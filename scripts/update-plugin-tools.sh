#!/usr/bin/env bash
set -euo pipefail

# Writes the "Plugins and their tools" part of README.md from
# Resources/plugins.json, so the tools, licences and repositories each plugin
# installs are listed in one place and never drift from what the app installs.
# The app links each plugin page to its section here.
#
# Usage: scripts/update-plugin-tools.sh          rewrite README.md
#        scripts/update-plugin-tools.sh --check  fail if README.md is out of date

root="$(cd "$(dirname "$0")/.." && pwd)"
catalog="$root/Resources/plugins.json"
readme="$root/README.md"
start='<!-- plugin-tools:start -->'
end='<!-- plugin-tools:end -->'

command -v jq >/dev/null || { echo "jq is required." >&2; exit 1; }
jq -e '.schemaVersion == 2 and (.plugins | type == "array")' "$catalog" >/dev/null
grep -qxF "$start" "$readme" && grep -qxF "$end" "$readme" ||
  { echo "README.md needs the lines $start and $end." >&2; exit 1; }

generated="$(mktemp)"
updated="$(mktemp)"
trap 'rm -f "$generated" "$updated"' EXIT

{
  echo "$start"
  echo "<!-- Generated by scripts/update-plugin-tools.sh from Resources/plugins.json. Edit those, not this. -->"
  jq -r '
    def installed:
      if startswith("homebrew:") then "Homebrew `\(ltrimstr("homebrew:"))`"
      elif startswith("source:") then
        (ltrimstr("source:")) as $rev
        | "Built from source at `\(if ($rev | test("^[0-9a-f]{40}$")) then $rev[0:12] else $rev end)`"
      elif startswith("npm:") then "npm `\(ltrimstr("npm:"))`"
      else "—" end;
    .plugins[]
    | "",
      "### \(.name)",
      "",
      "| Tool | Licence | Installed |",
      "| --- | --- | --- |",
      (.components[] | "| [\(.name)](\(.repository)) | \(.license // "See repository") | \(.install // "" | installed) |")
  ' "$catalog"
  echo
  echo "$end"
} > "$generated"

awk -v start="$start" -v end="$end" -v file="$generated" '
  $0 == start { while ((getline line < file) > 0) print line; skipping = 1; next }
  $0 == end { skipping = 0; next }
  !skipping { print }
' "$readme" > "$updated"

if [[ "${1:-}" == "--check" ]]; then
  if ! cmp -s "$readme" "$updated"; then
    echo "README.md's plugin tools are out of date. Run scripts/update-plugin-tools.sh and commit the result." >&2
    diff -u "$readme" "$updated" >&2 || true
    exit 1
  fi
  echo "README.md's plugin tools match Resources/plugins.json."
else
  cp "$updated" "$readme"
  echo "Updated README.md from Resources/plugins.json."
fi
